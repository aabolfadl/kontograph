"""Data lineage, rendered from the Dagster asset graph.

The platform scope: *"Model cards, data lineage, drift reports and decision logs are
generated by the pipeline, versioned, and reproducible from a commit hash."*

The diagram is derived from ``orchestration/dagster/definitions.py`` rather than
drawn by hand, which is the entire point: a hand-drawn lineage diagram is
accurate on the day it is drawn and misleading thereafter. If an asset is added
and this diagram does not change, the diagram is wrong — and there is a test
that says so.

Falls back to a static declaration when Dagster is not installed, because the
governance report should be producible without the orchestration extra. The
fallback is marked as such in the output rather than passed off as derived.
"""

from __future__ import annotations

import datetime as _dt
from dataclasses import dataclass
from pathlib import Path

from kg_core.logging import get_logger

log = get_logger(__name__)

#: Used when Dagster is unavailable. Kept in sync with definitions.py by
#: ``test_lineage_matches_the_asset_graph``.
STATIC_EDGES: tuple[tuple[str, str], ...] = (
    ("synthetic_dataset", "bronze_payments"),
    ("synthetic_dataset", "silver_accounts"),
    ("synthetic_dataset", "silver_labels"),
    ("bronze_payments", "silver_payments"),
    ("silver_accounts", "silver_payments"),
    ("silver_payments", "analytics_database"),
    ("silver_labels", "analytics_database"),
    ("analytics_database", "gold_marts"),
)

#: Which blocking checks guard which asset. Read by the governance report so an
#: auditor can see the gates, not just the flow.
ASSET_CHECKS: dict[str, tuple[tuple[str, bool], ...]] = {
    "synthetic_dataset": (("dataset_is_reproducible", True),),
    "bronze_payments": (
        ("bronze_quality_gate", True),
        ("bronze_distribution_warnings", False),
    ),
    "silver_payments": (
        ("silver_referential_integrity", True),
        ("labels_never_precede_their_events", True),
    ),
}

LAYERS: dict[str, str] = {
    "synthetic_dataset": "source",
    "bronze_payments": "bronze",
    "silver_accounts": "silver",
    "silver_labels": "silver",
    "silver_payments": "silver",
    "analytics_database": "gold",
    "gold_marts": "gold",
}


@dataclass(slots=True)
class Lineage:
    """The asset graph, and where it came from."""

    edges: tuple[tuple[str, str], ...]
    derived: bool
    source: str

    @property
    def assets(self) -> list[str]:
        seen: list[str] = []
        for upstream, downstream in self.edges:
            for node in (upstream, downstream):
                if node not in seen:
                    seen.append(node)
        return seen


def collect() -> Lineage:
    """Read the lineage from the Dagster definitions, or fall back."""
    try:
        import importlib.util

        from kg_core.config import get_settings

        path = get_settings().repo_root / "orchestration" / "dagster" / "definitions.py"
        spec = importlib.util.spec_from_file_location("kg_dagster_defs", path)
        if spec is None or spec.loader is None:
            raise ImportError("cannot load the Dagster definitions")
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        edges = tuple(module.lineage_edges())
        return Lineage(edges=edges, derived=True, source=str(path))
    except Exception as error:
        log.info("using the static lineage declaration", reason=str(error))
        return Lineage(
            edges=STATIC_EDGES,
            derived=False,
            source="kg_gov.lineage.STATIC_EDGES (Dagster not available)",
        )


def render_mermaid(lineage: Lineage) -> str:
    """The asset graph as a Mermaid diagram, grouped by medallion layer."""
    grouped: dict[str, list[str]] = {}
    for asset in lineage.assets:
        grouped.setdefault(LAYERS.get(asset, "other"), []).append(asset)

    lines = ["```mermaid", "flowchart LR"]
    for layer in ("source", "bronze", "silver", "gold", "other"):
        assets = grouped.get(layer)
        if not assets:
            continue
        lines.append(f'  subgraph {layer.upper()}["{layer}"]')
        for asset in assets:
            checks = ASSET_CHECKS.get(asset, ())
            blocking = sum(1 for _, is_blocking in checks if is_blocking)
            label = asset.replace("_", " ")
            if blocking:
                label += f"<br/><i>{blocking} blocking check{'s' if blocking > 1 else ''}</i>"
            lines.append(f'    {asset}["{label}"]')
        lines.append("  end")

    for upstream, downstream in lineage.edges:
        lines.append(f"  {upstream} --> {downstream}")
    lines.append("```")
    return "\n".join(lines)


def render_report(lineage: Lineage, *, dataset: str | None = None) -> str:
    """The full lineage document."""
    generated = _dt.datetime.now(tz=_dt.UTC).strftime("%Y-%m-%d %H:%M UTC")
    provenance = (
        "Derived from the Dagster asset graph at "
        f"`{Path(lineage.source).name}`. If an asset is added and this diagram does not "
        "change, the diagram is wrong."
        if lineage.derived
        else "**Static fallback** — Dagster is not installed in this environment, so the "
        "diagram is read from a declaration rather than derived. Install the "
        "`orchestration` extra to generate it from the real graph."
    )

    lines = [
        "# Data lineage",
        "",
        f"> Generated {generated} by `kg gov lineage`. {provenance}",
        "",
        render_mermaid(lineage),
        "",
        "## Assets",
        "",
        "| Asset | Layer | Depends on | Blocking checks |",
        "|---|---|---|---|",
    ]
    upstreams: dict[str, list[str]] = {}
    for upstream, downstream in lineage.edges:
        upstreams.setdefault(downstream, []).append(upstream)

    for asset in lineage.assets:
        checks = ASSET_CHECKS.get(asset, ())
        blocking = [name for name, is_blocking in checks if is_blocking]
        lines.append(
            f"| `{asset}` | {LAYERS.get(asset, '—')} | "
            f"{', '.join(f'`{u}`' for u in upstreams.get(asset, [])) or '—'} | "
            f"{', '.join(f'`{c}`' for c in blocking) or '—'} |"
        )

    lines += [
        "",
        "## What the blocking checks guarantee",
        "",
        "A failing blocking check stops downstream assets from materialising. These are not "
        "assertions buried inside a transform — they are Dagster asset checks, visible in the "
        "UI and in the run history.",
        "",
        "| Check | Guards against |",
        "|---|---|",
        "| `dataset_is_reproducible` | the dataset no longer regenerating byte-identically, "
        "which is the premise ADR-0009 rests on when it replaces DVC with content hashing |",
        "| `bronze_quality_gate` | structurally invalid payments reaching silver. On its first "
        "run it blocked a promotion on `debtor_and_creditor_differ` and exposed a real "
        "simulator bug |",
        "| `silver_referential_integrity` | dangling account references, which would make a "
        "mart quietly produce nulls instead of failing |",
        "| `labels_never_precede_their_events` | a label decided before its transaction "
        "happened — a time-travel bug, caught at the cheapest possible place |",
        "",
        "## Time travel",
        "",
        "Every Iceberg table keeps its snapshot history, so the state of any layer at any past "
        "instant is recoverable:",
        "",
        "```bash",
        "kg lake history bronze.payments   # snapshot id, parent, timestamp, records added",
        "kg lake status                    # row counts and snapshot counts per table",
        "```",
        "",
        "The DuckDB analytics database records which Iceberg snapshot each mart was built from, "
        "in its `_lineage` table — so a number in a mart is traceable to the exact table state "
        "that produced it.",
    ]
    if dataset:
        lines += ["", f"_Current dataset: `{dataset}`_"]
    return "\n".join(lines)


def generate(output: Path, *, dataset: str | None = None) -> Path:
    lineage = collect()
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render_report(lineage, dataset=dataset), encoding="utf-8")
    return output
