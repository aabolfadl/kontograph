"""Model cards, generated from run artifacts.

Design principle P8: *"Governance is code or it is theatre."* A model card written by
hand is a document that was true once. This one is assembled from the evaluation
report, the dataset manifest and the feature-set fingerprint, so it cannot
describe a model other than the one that was actually trained — and regenerating
it after a change produces a different card rather than a stale one.

The sections follow the Model Cards for Model Reporting structure, with two
additions this domain requires:

**Label provenance.** The card states how many of the true positives the label
stream actually captured. Any card reporting precision without that number is
reporting an upper bound as though it were a measurement.

**The regulatory position.** Which instrument governs this model, and — as
importantly — which does not. Getting that distinction right is the domain
expertise (the regulatory context); asserting "EU AI Act compliant" without it is not.
"""

from __future__ import annotations

import datetime as _dt
import json
from pathlib import Path
from typing import Any

from kg_core.hashing import content_hash


def _fmt(value: Any, digits: int = 4) -> str:
    if isinstance(value, (int, float)):
        return f"{value:.{digits}f}" if isinstance(value, float) else f"{value:,}"
    return str(value)


def _interval(entry: dict[str, Any] | None) -> str:
    if not entry:
        return "—"
    return f"{entry['point']:.4f} [{entry['ci_low']:.4f}, {entry['ci_high']:.4f}]"


def render(report: dict[str, Any], *, model: str = "lightgbm") -> str:
    """Render the model card for one model in an evaluation report."""
    context = report.get("context", {})
    capacity = context.get("capacity_per_day", 200)
    results = [r for r in report.get("results", []) if r["fold"] == "test" and r["model"] == model]
    if not results:
        return f"_No test results for `{model}` in this report._"
    result = results[0]
    metrics = result["metrics"]
    intervals = result.get("intervals", {})

    gap = context.get("label_gap") or {}
    oracle = (context.get("oracle_comparison") or {}).get(model, {})
    folds = context.get("folds", {})
    cost = context.get("cost_model", {})
    split = context.get("split", {}).get("boundaries", {})

    generated = _dt.datetime.now(tz=_dt.UTC).strftime("%Y-%m-%d %H:%M UTC")

    lines = [
        f"# Model card — `{model}`",
        "",
        "> Generated by `kg gov model-card` from run artifacts. Every figure below is read "
        "from a file produced by the training run; none is typed by hand. Regenerating this "
        "card after any change produces a different card rather than a stale one.",
        "",
        "| | |",
        "|---|---|",
        f"| Generated | {generated} |",
        f"| Dataset | `{report.get('dataset', '—')}` |",
        f"| Feature set | `{report.get('feature_set_fingerprint', '—')}` |",
        f"| Code commit | `{report.get('code_commit', '—')}` |",
        f"| Evaluation protocol | `{report.get('protocol_hash', '—')[:16]}` |",
        "",
        "---",
        "",
        "## Intended use",
        "",
        "Scores individual SEPA Instant Credit Transfers for financial-crime risk, inside the "
        "ten-second settlement window, to raise an alert for human review.",
        "",
        "**In scope.** Ranking transactions for a compliance analyst's queue; supplying the "
        "explanation that accompanies an alert.",
        "",
        "**Out of scope, explicitly.** Creditworthiness assessment, automated account closure, "
        "and any decision taken without human review. This is a *triage* model: it decides what "
        "a person looks at, not what happens to a customer.",
        "",
        "## Regulatory position",
        "",
        "AML transaction monitoring is **not** an Annex III high-risk system under the EU AI "
        "Act. It is governed by the AML package (AMLR/AMLD) and BaFin's interpretive guidance, "
        "with DORA and MaRisk applying to its operational resilience and model risk management.",
        "",
        "Creditworthiness assessment *is* Annex III high-risk — and this model does not perform "
        'it. Stating that distinction precisely is the point; a card claiming blanket "AI Act '
        'compliance" for an AML model would be describing the wrong instrument.',
        "",
        "Because scores contribute to automated decisions affecting individuals, **DSGVO/GDPR "
        "Art. 22** applies. See `docs/ai-act-memo.md` for the full analysis and "
        "`kg serve verify-log` for the decision log that supports it.",
        "",
        "---",
        "",
        "## Performance",
        "",
        f"Evaluated on the held-out test fold. `k` = {capacity} alerts/day, the stated analyst "
        "capacity, fixed in the protocol before training.",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| PR-AUC (95% CI) | {_interval(intervals.get('pr_auc'))} |",
        f"| Precision@{capacity}/day | {_fmt(metrics.get(f'precision_at_{capacity}_per_day'))} |",
        f"| Recall@{capacity}/day | {_fmt(metrics.get(f'recall_at_{capacity}_per_day'))} |",
        f"| Expected cost / 10k tx | €{metrics.get('expected_cost_per_10k', 0):,.0f} |",
        f"| Brier score | {_fmt(metrics.get('brier'), 6)} |",
        f"| Expected calibration error | {_fmt(metrics.get('ece'), 6)} |",
        f"| ROC-AUC | {_fmt(metrics.get('roc_auc'))} _(not a headline — see below)_ |",
        "",
        "**ROC-AUC is reported but not headlined.** At this class balance it is dominated by "
        "the negative class: a model can score 0.85 there while its top alerts are almost all "
        "false positives. PR-AUC and precision@k are the metrics that notice.",
        "",
    ]

    if gap:
        lines += [
            "## What the labels can and cannot show",
            "",
            f"The label stream captured **{gap.get('recall_of_truth', 0):.1%}** of the crime "
            f"actually present — {int(gap.get('labelled_positives', 0)):,} of "
            f"{int(gap.get('true_positives', 0)):,} transactions.",
            "",
            "Every precision figure above is therefore an **upper bound**: transactions that are "
            "genuinely criminal but were never confirmed sit in the negative class and count "
            "against precision when the model finds them.",
            "",
        ]
        if oracle:
            lines += [
                "| Scored against | PR-AUC |",
                "|---|---|",
                f"| the label stream | {_fmt(oracle.get('pr_auc_vs_labels'))} |",
                f"| ground truth | {_fmt(oracle.get('pr_auc_vs_oracle'))} |",
                "",
                "The second row is only computable because the data is simulated. A real "
                "institution could not produce it — which is precisely why the simulator exists "
                "(design principle P9).",
                "",
            ]

    if folds:
        lines += [
            "## Training data",
            "",
            "| Fold | Period | Rows | Positives | Rate | Label coverage |",
            "|---|---|---|---|---|---|",
        ]
        for name in ("train", "validation", "test"):
            entry = folds.get(name, {})
            lines.append(
                f"| {name} | {split.get(name, '—')} | {entry.get('rows', 0):,} | "
                f"{entry.get('positives', 0)} | {entry.get('positive_rate', 0):.4%} | "
                f"{entry.get('label_coverage', 0):.4%} |"
            )
        lines += [
            "",
            "Splits are **chronological**, never random. A label enters a fold only if its "
            "`decided_ts` precedes that fold's boundary — a label whose transaction is in the "
            "training window but whose decision came later does not exist as far as training is "
            "concerned.",
            "",
            "**The data is synthetic.** It is generated by an agent-based simulator of a German "
            "retail payments ecosystem, calibrated against public aggregates. It is described as "
            "a simulator throughout and is not presented as real customer data.",
            "",
        ]

    if cost:
        lines += [
            "## Cost model",
            "",
            "The operating threshold minimises expected cost on the **validation** fold and is "
            "applied unchanged to test. Choosing it on test is the commonest way a result is "
            "overstated, and it is invisible in the final table.",
            "",
            "| Parameter | Value |",
            "|---|---|",
            f"| Investigation cost | €{cost.get('investigation_eur', 0):.2f} |",
            f"| Customer friction | €{cost.get('friction_eur', 0):.2f} |",
            f"| False positive (total) | €{cost.get('false_positive_eur', 0):.2f} |",
            f"| Loss prevented by alerting in time | {cost.get('prevention_fraction', 0):.0%} |",
            "",
            f"_{cost.get('note', '')}_",
            "",
        ]

    importance = result.get("importance", [])
    if importance:
        lines += [
            "## What the model uses",
            "",
            "Gain-based importance. Gain rather than split count, because split count rewards "
            "high-cardinality features for being splittable.",
            "",
            "| Feature | Share of gain |",
            "|---|---|",
        ]
        lines += [f"| `{e['feature']}` | {e['share']:.1%} |" for e in importance[:10]]
        lines.append("")

    parity = _serving_parity(report)
    if parity:
        lines += [
            "## Serving artifact",
            "",
            "A model card should say which artifact actually makes the decisions, because a "
            "format conversion is a model change until measured otherwise.",
            "",
            f"**The gateway serves the LightGBM booster in-process.** An ONNX graph is exported "
            f"alongside it for portability, and it is *not* the serving path: scored against "
            f"{parity['rows']:,} held-out feature vectors it changes "
            f"{parity['decisions_changed']:,} decisions "
            f"({parity['decisions_changed_share']:.4%}) and raises "
            f"{parity['alerts_onnx']:,} alerts where this model raises "
            f"{parity['alerts_booster']:,} — an alert-set Jaccard of "
            f"{parity['alert_jaccard']:.4f}.",
            "",
            "The cause is precision: ONNX scores tree ensembles in float32, LightGBM accumulates "
            f"in float64, and the operating threshold of {parity['threshold']:.2e} is small "
            "enough that the rounding crosses it. See "
            "[ADR-0008](../adr/0008-onnx-runtime-not-triton.md).",
            "",
        ]

    lines += [
        "## Known limitations",
        "",
        "- **Trained on simulated data.** Behaviour on real payment traffic is unknown. The "
        "simulator's calibration targets are public aggregates, not licensed microdata.",
        "- **Labels are incomplete and selection-biased.** Confirmation requires the incumbent "
        "rules engine to have flagged the case first, so the label stream systematically "
        "under-represents evasive typologies.",
        "- **Precision figures are upper bounds** for the reason stated above.",
        "- **No fairness assessment has been performed.** The simulator generates names "
        "reflecting Germany's largest immigrant communities, which means a disparate-impact "
        "analysis across name origin is *possible* and has not been done. That is a gap, not an "
        "absence of risk.",
        "- **Concept drift is unmeasured over long horizons.** The evaluation covers a single "
        "simulated period.",
        "",
        "## Reproducing this card",
        "",
        "```bash",
        "make pipeline          # simulator -> bronze -> silver -> gold -> features",
        "kg train baseline      # train, calibrate, threshold, evaluate",
        "kg gov model-card      # regenerate this document",
        "```",
        "",
        f"_Card fingerprint: `{content_hash(report, prefix='model-card')[:16]}`_",
    ]
    return "\n".join(lines)


def _serving_parity(report: dict[str, Any]) -> dict[str, Any] | None:
    """Load the ONNX parity measurement, if one has been taken.

    Read from the artifact rather than passed in, so the card cannot quote a
    parity result that no run produced. Absent means absent: the section is
    omitted rather than filled with a reassuring default.
    """
    from kg_core.config import get_settings

    dataset = report.get("dataset")
    if not dataset:
        return None
    path = get_settings().artifacts_dir / "models" / dataset / "lightgbm" / "onnx_parity.json"
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def generate(report_path: Path, output: Path, *, model: str = "lightgbm") -> Path:
    """Read an evaluation report and write the model card."""
    report = json.loads(report_path.read_text(encoding="utf-8"))
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(report, model=model), encoding="utf-8")
    return output
