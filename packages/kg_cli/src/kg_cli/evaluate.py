"""``kg train`` and ``kg eval`` — the ablation ladder and its report."""

from __future__ import annotations

import json
from pathlib import Path
from typing import TYPE_CHECKING, Any

import typer
from rich.console import Console
from rich.table import Table

from kg_core.config import get_settings

if TYPE_CHECKING:
    from kg_eval.report import EvaluationReport

train_app = typer.Typer(name="train", help="Train the ablation ladder.", no_args_is_help=True)
eval_app = typer.Typer(
    name="eval", help="Regenerate every published number from artifacts.", no_args_is_help=True
)
console = Console()


def _resolve(features: Path | None, dataset: Path | None) -> tuple[Path, Path]:
    from kg_sim.dataset import find_latest

    settings = get_settings()
    dataset_dir = dataset or find_latest(settings.data_dir)
    if dataset_dir is None:
        console.print("[red]no dataset found.[/] Run `kg sim generate` first.")
        raise typer.Exit(1)

    features_path = features or (
        settings.artifacts_dir / "features" / f"{dataset_dir.name}.parquet"
    )
    if not features_path.exists():
        console.print(
            f"[red]no feature table at {features_path}.[/] Run `kg features build` first."
        )
        raise typer.Exit(1)
    return features_path, dataset_dir


@train_app.command("baseline")
def train_baseline(
    features: Path = typer.Option(None, "--features"),
    dataset: Path = typer.Option(None, "--dataset"),
    capacity: int = typer.Option(None, "--capacity", help="Alerts per day (the k in precision@k)."),
    max_alert_rate: float = typer.Option(0.01, "--max-alert-rate"),
    resamples: int = typer.Option(2_000, "--resamples", help="Bootstrap resamples."),
    label_delay: float = typer.Option(0.0, "--label-delay-days"),
    out: Path = typer.Option(None, "--out", help="Where to write the report."),
) -> None:
    """Train rungs 0 and 1, evaluate on test, and write the report.

    Rung 0 is a constant predictor. It is not a joke entry: it establishes what
    "no model" scores on every metric, which is the only way to read the others.
    """
    from kg_models.runner import RunConfig, run

    settings = get_settings()
    settings.ensure_dirs()
    features_path, dataset_dir = _resolve(features, dataset)

    config = RunConfig(
        features_path=features_path,
        dataset_dir=dataset_dir,
        capacity_per_day=capacity or settings.analyst_capacity_per_day,
        max_alert_rate=max_alert_rate,
        bootstrap_resamples=resamples,
        label_delay_days=label_delay,
    )

    # Snapshot any existing report BEFORE training: report.write() replaces the
    # file wholesale, and rungs 2-5 come from GPU runs this command cannot redo.
    existing = settings.artifacts_dir / "eval" / f"{dataset_dir.name}.json"
    if existing.exists():
        import shutil

        shutil.copy2(existing, existing.with_suffix(".json.pre-retrain"))

    console.print(f"training on [bold]{dataset_dir.name}[/] ({features_path.name})")
    with console.status("running the ladder…"):
        report, models, data = run(config)

    for name, model in models.items():
        directory = settings.artifacts_dir / "models" / dataset_dir.name / name
        model.save(directory)
        _save_test_scores(model, data, directory)

    destination = out or (settings.artifacts_dir / "eval" / f"{dataset_dir.name}.json")
    report.write(destination)
    _restore_gpu_rungs(destination)

    _print_report(report)
    console.print(f"\n[green]report written[/] {destination}")


def _restore_gpu_rungs(destination: Path) -> None:
    """Carry GPU-trained rungs across a local retrain.

    ``report.write`` replaces the file, so a retrain would silently delete rungs
    2-5 — results that cost a GPU session and cannot be regenerated by this
    command. They are re-attached here, and re-ingesting is idempotent anyway,
    so nothing is lost either way.

    Reads the previous file rather than tracking state, because the failure this
    guards against is precisely someone running `kg train baseline` without
    remembering the ladder is in there.
    """
    import json

    backup = destination.with_suffix(".json.pre-retrain")
    if not backup.exists():
        return

    previous = json.loads(backup.read_text(encoding="utf-8"))
    carried = [
        r for r in previous.get("results", []) if str(r.get("source", "")).startswith("kaggle:")
    ]
    if not carried:
        backup.unlink()
        return

    current = json.loads(destination.read_text(encoding="utf-8"))
    names = {r["model"] for r in current.get("results", [])}
    current["results"].extend(r for r in carried if r["model"] not in names)
    current.setdefault("comparisons", []).extend(
        c
        for c in previous.get("comparisons", [])
        if str(c.get("model", "")).startswith(("2_", "3_", "4_", "5_"))
    )
    destination.write_text(json.dumps(current, indent=2), encoding="utf-8")
    backup.unlink()
    console.print(
        f"[dim]carried {len(carried)} GPU-trained rung(s) across the retrain; "
        "re-run `kg eval ingest-gpu` if the dataset changed.[/]"
    )


def _save_test_scores(model: Any, data: Any, directory: Path) -> None:
    """Persist this model's test-fold scores, keyed by transaction id.

    Needed for the paired bootstrap against rungs trained elsewhere: comparing a
    GPU-trained model to this one requires both score vectors over the same
    rows, and re-deriving them later means re-training. Stored with the ids
    rather than as a bare array, because the two sides build their orderings
    independently and aligning by position would be a guess that usually looks
    right.
    """
    import numpy as np

    from kg_eval.splits import Fold

    X_test, _, rows = data.matrix(Fold.TEST)
    np.savez_compressed(
        directory / "test_scores.npz",
        tx_ids=data.tx_ids[rows].astype(str),
        scores=model.predict(X_test),
    )


def _print_report(report: EvaluationReport) -> None:
    from kg_eval.report import render_verdict

    capacity = report.context["capacity_per_day"]
    split = report.context["split"]["counts"]
    folds = report.context["folds"]

    console.print("\n[bold]Split[/]")
    fold_table = Table("fold", "rows", "positives", "rate", "label coverage")
    for name in ("train", "validation", "test"):
        entry = folds[name]
        fold_table.add_row(
            name,
            f"{entry['rows']:,}",
            str(entry["positives"]),
            f"{entry['positive_rate']:.4%}",
            f"{entry['label_coverage']:.4%}",
        )
    console.print(fold_table)
    console.print(
        f"[dim]purged {split.get('purged', 0):,} · embargoed {split.get('embargoed', 0):,}[/]"
    )

    console.print("\n[bold]Test results[/]")
    table = Table(
        "model", "PR-AUC (95% CI)", f"P@{capacity}/d", f"R@{capacity}/d", "cost/10k", "ROC-AUC"
    )
    for result in report.for_fold("test"):
        metrics = result.bundle.metrics
        interval = result.intervals.get("pr_auc")
        table.add_row(
            result.model,
            interval.format() if interval else f"{metrics['pr_auc'].value:.4f}",
            f"{metrics[f'precision_at_{capacity}_per_day'].value:.4f}",
            f"{metrics[f'recall_at_{capacity}_per_day'].value:.4f}",
            f"€{metrics['expected_cost_per_10k'].value:,.0f}"
            if "expected_cost_per_10k" in metrics
            else "—",
            f"[dim]{metrics['roc_auc'].value:.4f}[/]",
        )
    console.print(table)
    console.print("[dim]ROC-AUC is dimmed deliberately: at this class balance it is decoration.[/]")

    console.print("\n[bold]Verdict[/]")
    console.print(render_verdict(report))

    gap = report.context.get("label_gap")
    if gap:
        console.print(
            f"\n[bold]Label bias[/] — the label stream captures "
            f"[bold]{gap['recall_of_truth']:.1%}[/] of the crime actually injected "
            f"({int(gap['labelled_positives']):,} of {int(gap['true_positives']):,}). "
            "Every precision figure above is an upper bound."
        )

    oracle = report.context.get("oracle_comparison")
    if oracle:
        oracle_table = Table("model", "PR-AUC vs labels", "PR-AUC vs ground truth")
        for name, entry in oracle.items():
            oracle_table.add_row(
                name, f"{entry['pr_auc_vs_labels']:.4f}", f"{entry['pr_auc_vs_oracle']:.4f}"
            )
        console.print(oracle_table)

    top = next((r for r in report.for_fold("test") if r.model == "lightgbm"), None)
    if top and top.extras.get("importance"):
        console.print("\n[bold]What the model actually used[/]")
        importance = Table("feature", "share of gain")
        for entry in top.extras["importance"][:8]:
            importance.add_row(entry["feature"], f"{entry['share']:.1%}")
        console.print(importance)


@eval_app.command("report")
def report_command(
    dataset: Path = typer.Option(None, "--dataset"),
    markdown: bool = typer.Option(False, "--markdown", help="Emit the README results section."),
    out: Path = typer.Option(None, "--out"),
) -> None:
    """Render the results from a stored report. Regenerates, never invents."""
    from kg_eval.bootstrap import Interval
    from kg_eval.metrics import Metric, MetricBundle
    from kg_eval.report import EvaluationReport, RunResult, render_summary
    from kg_sim.dataset import find_latest

    settings = get_settings()
    dataset_dir = dataset or find_latest(settings.data_dir)
    if dataset_dir is None:
        console.print("[red]no dataset found.[/] Run `kg sim generate` first.")
        raise typer.Exit(1)
    path = settings.artifacts_dir / "eval" / f"{dataset_dir.name}.json"
    if not path.exists():
        console.print(f"[red]no report at {path}.[/] Run `kg train baseline` first.")
        raise typer.Exit(1)

    payload = json.loads(path.read_text(encoding="utf-8"))
    report = EvaluationReport(
        dataset=payload["dataset"],
        feature_set_fingerprint=payload["feature_set_fingerprint"],
        code_commit=payload["code_commit"],
        protocol_hash=payload["protocol_hash"],
        context=payload["context"],
    )
    for entry in payload["results"]:
        bundle = MetricBundle()
        for name, value in entry["metrics"].items():
            bundle.add(Metric(name, value, headline=name in entry.get("headline", [])))
        result = RunResult(model=entry["model"], fold=entry["fold"], bundle=bundle)
        for name, interval in entry.get("intervals", {}).items():
            result.intervals[name] = Interval(
                interval["point"], interval["ci_low"], interval["ci_high"]
            )
        report.add(result)

    from kg_eval.bootstrap import Comparison

    for entry in payload.get("comparisons", []):
        difference = entry["difference"]
        report.comparisons.append(
            Comparison(
                metric=entry["metric"],
                model_a=entry["a"],
                model_b=entry["b"],
                difference=Interval(
                    difference["point"], difference["ci_low"], difference["ci_high"]
                ),
            )
        )

    if markdown:
        text = render_summary(report)
        if out:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text, encoding="utf-8")
            console.print(f"[green]written[/] {out}")
        else:
            console.print(text)
        return

    _print_report(report)


@eval_app.command("label-delay")
def label_delay(
    features: Path = typer.Option(None, "--features"),
    dataset: Path = typer.Option(None, "--dataset"),
    delays: str = typer.Option("0,14,30,60", "--delays", help="Comma-separated days."),
) -> None:
    """Retrain under increasing verification latency — protocol §7.

    Almost nobody does this. It is what turns "labels arrive late" from a caveat
    into a measured decay curve.
    """
    from kg_models.runner import RunConfig, label_delay_curve

    settings = get_settings()
    features_path, dataset_dir = _resolve(features, dataset)
    values = tuple(float(part) for part in delays.split(","))

    config = RunConfig(
        features_path=features_path,
        dataset_dir=dataset_dir,
        capacity_per_day=settings.analyst_capacity_per_day,
        # A smaller bootstrap: this runs the whole ladder once per delay, and
        # the curve's shape is the finding, not the interval on each point.
        bootstrap_resamples=200,
    )
    console.print(f"retraining at label delays: {values} days")
    curve = label_delay_curve(config, values)

    table = Table(
        "delay (days)", "training positives", "PR-AUC", f"P@{settings.analyst_capacity_per_day}"
    )
    for point in curve:
        table.add_row(
            f"{point['delay_days']:.0f}",
            f"{point['training_positives']:,}",
            f"{point['pr_auc']:.4f}",
            f"{point[f'precision_at_{settings.analyst_capacity_per_day}']:.4f}",
        )
    console.print(table)

    destination = settings.artifacts_dir / "eval" / f"{dataset_dir.name}-label-delay.json"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(curve, indent=2), encoding="utf-8")
    console.print(f"[green]written[/] {destination}")


